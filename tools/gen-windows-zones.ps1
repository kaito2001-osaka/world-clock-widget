# Generates the IANA -> Windows time zone table that the gadget and the
# settings app share (#49): src/clock/WindowsZoneMap.cpp and
# src/settings/WindowsZoneMap.g.cs.
#
# The source is CLDR: common/supplemental/windowsZones.xml maps IANA ids to
# Windows zone ids, and common/bcp47/timezone.xml lists every alias of each
# zone. CLDR keys windowsZones by its own canonical names, some of them the
# old spellings (Asia/Calcutta, America/Godthab), so the aliases are needed to
# resolve the names users type today (Asia/Kolkata, America/Nuuk).
#
# Usage: powershell -File tools\gen-windows-zones.ps1 [-Tag release-49]
# Re-run with a newer tag when CLDR changes a mapping; commit both outputs.
param(
    [string]$Tag = 'release-49'
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot

# The XML is only parsed, never executed.
$base = "https://raw.githubusercontent.com/unicode-org/cldr/$Tag/common"
[xml]$windowsZones = (Invoke-WebRequest -UseBasicParsing "$base/supplemental/windowsZones.xml").Content
[xml]$bcp47        = (Invoke-WebRequest -UseBasicParsing "$base/bcp47/timezone.xml").Content

# CLDR id -> Windows id. One IANA id appears under several territories (the
# "001" golden zone and its own country), always with the same Windows id.
$map = @{}
foreach ($z in $windowsZones.supplementalData.windowsZones.mapTimezones.mapZone) {
    foreach ($id in ($z.type -split ' ')) {
        if (-not $id) { continue }
        if ($map.ContainsKey($id) -and $map[$id] -ne $z.other) {
            throw "$id maps to both '$($map[$id])' and '$($z.other)'"
        }
        $map[$id] = $z.other
    }
}

# Extend to every alias of a mapped zone.
$all = @{}
foreach ($k in $map.Keys) { $all[$k] = $map[$k] }
foreach ($t in $bcp47.ldmlBCP47.keyword.key.type) {
    if ($t.deprecated -eq 'true' -or -not $t.alias) { continue }
    $names = @($t.alias -split ' ' | Where-Object { $_ })
    if ($t.iana) { $names += $t.iana }
    $windows = $names | Where-Object { $map.ContainsKey($_) } | ForEach-Object { $map[$_] } | Select-Object -Unique
    if (@($windows).Count -gt 1) { throw "aliases '$($t.alias)' map to several Windows zones" }
    if (-not $windows) { continue }
    foreach ($n in $names) { $all[$n] = $windows }
}

# Ordinal order, so the C++ side can binary-search with plain string compares.
$keys = [string[]]$all.Keys
[Array]::Sort($keys, [StringComparer]::Ordinal)
$header = "Generated by tools/gen-windows-zones.ps1 from CLDR $Tag. Do not edit."

$cpp = [System.Collections.Generic.List[string]]::new()
$cpp.Add("// $header")
$cpp.Add('#include "WindowsZoneMap.hpp"')
$cpp.Add('')
$cpp.Add('#include <algorithm>')
$cpp.Add('#include <iterator>')
$cpp.Add('')
$cpp.Add('namespace {')
$cpp.Add('constexpr WindowsZoneEntry kZones[] = {')
foreach ($k in $keys) { $cpp.Add("    { `"$k`", L`"$($all[$k])`" },") }
$cpp.Add('};')
$cpp.Add('} // namespace')
$cpp.Add('')
$cpp.Add('const wchar_t* WindowsZoneId(std::string_view iana) {')
$cpp.Add('    auto it = std::lower_bound(std::begin(kZones), std::end(kZones), iana,')
$cpp.Add('                               [](const WindowsZoneEntry& e, std::string_view v) { return e.iana < v; });')
$cpp.Add('    return (it != std::end(kZones) && it->iana == iana) ? it->windows : nullptr;')
$cpp.Add('}')
$cpp.Add('')
$cpp.Add('std::span<const WindowsZoneEntry> AllWindowsZones() { return kZones; }')

$cs = [System.Collections.Generic.List[string]]::new()
$cs.Add("// $header")
$cs.Add('namespace WorldClockSettings;')
$cs.Add('')
$cs.Add('public static class WindowsZoneMap')
$cs.Add('{')
$cs.Add('    // IANA id (exact spelling) -> Windows time zone id.')
$cs.Add('    public static readonly IReadOnlyDictionary<string, string> Zones = new Dictionary<string, string>(StringComparer.Ordinal)')
$cs.Add('    {')
foreach ($k in $keys) { $cs.Add("        [`"$k`"] = `"$($all[$k])`",") }
$cs.Add('    };')
$cs.Add('}')

$utf8 = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllLines((Join-Path $root 'src\clock\WindowsZoneMap.cpp'), $cpp, $utf8)
[IO.File]::WriteAllLines((Join-Path $root 'src\settings\WindowsZoneMap.g.cs'), $cs, $utf8)
Write-Host "$($keys.Count) names -> $(@($all.Values | Select-Object -Unique).Count) Windows zones (CLDR $Tag)"
